    function exportReportToPDF(elementId, filename, reportTitle) {
        const el = document.getElementById(elementId);
        if (!el) {
            alert('Report content not found!');
            return;
        }

        if (typeof html2pdf !== 'undefined') {
            const clone = el.cloneNode(true);
            clone.querySelectorAll('.no-print, button, form, input, .btn, .btn-outline, a.btn, a.btn-outline').forEach(node => node.remove());

            const header = document.createElement('div');
            header.style.cssText = 'padding:16px 20px; margin-bottom:20px; border-bottom:2px solid #6366f1; background:#ffffff; font-family:sans-serif; color:#0f172a;';
            header.innerHTML = `
                <div style="display:flex; justify-content:space-between; align-items:center;">
                    <div>
                        <h1 style="font-size:22px; font-weight:800; margin:0; color:#0f172a; letter-spacing:-0.5px;">DIGITAL LIBRARY</h1>
                        <h3 style="font-size:14px; font-weight:600; margin:4px 0 0 0; color:#475569;">${reportTitle || 'Author Performance Report'}</h3>
                    </div>
                    <div style="text-align:right; font-size:11px; color:#64748b; line-height:1.4;">
                        <div>Date: ${new Date().toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' })}</div>
                        <div>Generated by Author</div>
                    </div>
                </div>
            `;

            const wrapper = document.createElement('div');
            wrapper.style.cssText = 'background:#ffffff; color:#0f172a; padding:20px; font-family:sans-serif; width:100%; box-sizing:border-box;';
            wrapper.appendChild(header);
            wrapper.appendChild(clone);

            wrapper.querySelectorAll('*').forEach(node => {
                node.style.color = '#0f172a';
                if (node.tagName === 'TABLE') {
                    node.style.width = '100%';
                    node.style.borderCollapse = 'collapse';
                    node.style.marginTop = '10px';
                    node.style.marginBottom = '20px';
                }
                if (node.tagName === 'TH') {
                    node.style.background = '#f1f5f9';
                    node.style.color = '#334155';
                    node.style.borderBottom = '2px solid #cbd5e1';
                    node.style.padding = '8px 10px';
                    node.style.fontSize = '11px';
                }
                if (node.tagName === 'TD') {
                    node.style.borderBottom = '1px solid #e2e8f0';
                    node.style.padding = '8px 10px';
                    node.style.fontSize = '12px';
                }
                if (node.classList.contains('glass-card') || node.classList.contains('section') || node.classList.contains('report-stat') || node.classList.contains('stat-card')) {
                    node.style.background = '#f8fafc';
                    node.style.border = '1px solid #e2e8f0';
                    node.style.borderRadius = '8px';
                    node.style.padding = '16px';
                    node.style.marginBottom = '16px';
                    node.style.boxShadow = 'none';
                }
            });

            const opt = {
                margin:       [0.4, 0.4, 0.4, 0.4],
                filename:     (filename || 'DigitalLibrary_Author_Report') + '.pdf',
                image:        { type: 'jpeg', quality: 0.98 },
                html2canvas:  { scale: 2, useCORS: true, logging: false },
                jsPDF:        { unit: 'in', format: 'a4', orientation: 'portrait' }
            };

            html2pdf().set(opt).from(wrapper).save().catch(err => {
                console.error('html2pdf export failed:', err);
                window.print();
            });
        } else {
            window.print();
        }
    }
